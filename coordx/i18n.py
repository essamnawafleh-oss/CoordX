def set_lang(lang: str):
    global _lang
    _lang = "en" if lang == "en" else "ar"


def lang() -> str:
    return _lang


def tr(key: str, **kw) -> str:
    pair = S.get(key)
    if pair is None:
        return key
    text = pair[0] if _lang == "ar" else pair[1]
    return text.format(**kw) if kw else text
